private const val TAG = "GoogleAuthHelper"

fun FirebaseAuth.authStateFlow(): Flow<FirebaseUser?> = callbackFlow {
    val listener = FirebaseAuth.AuthStateListener { auth ->
        trySend(auth.currentUser)
    }
    addAuthStateListener(listener)
    awaitClose { removeAuthStateListener(listener) }
}

fun attemptAutoSignIn(
    context: Context,
    credentialManager: CredentialManager,
    onAuthSuccess: () -> Unit,
    onUnauthenticated: () -> Unit,
    scope: CoroutineScope
) {
    if (Firebase.auth.currentUser != null) {
        onAuthSuccess()
        return
    }
    val clientId = try {
        context.getString(R.string.default_web_client_id)
    } catch (_: Exception) {
        onUnauthenticated()
        return
    }
    val googleIdOption = GetGoogleIdOption.Builder()
        .setFilterByAuthorizedAccounts(true)
        .setServerClientId(clientId)
        .setAutoSelectEnabled(true)
        .build()
    val request = GetCredentialRequest.Builder()
        .addCredentialOption(googleIdOption)
        .build()

    scope.launch {
        try {
            val cred = credentialManager.getCredential(context, request).credential
            if (cred is CustomCredential && cred.type == TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                val token = GoogleIdTokenCredential.createFrom(cred.data).idToken
                Firebase.auth.signInWithCredential(GoogleAuthProvider.getCredential(token, null)).await()
                onAuthSuccess()
            } else {
                onUnauthenticated()
            }
        } catch (e: CancellationException) {
            throw e
        } catch (_: Exception) {
            onUnauthenticated()
        }
    }
}

fun onGoogleSignInClicked(
    context: Context,
    credentialManager: CredentialManager,
    onAuthSuccess: () -> Unit,
    onAuthError: (String) -> Unit,
    scope: CoroutineScope,
    onAuthCancelled: () -> Unit = {}
) {
    val clientId = try {
        context.getString(R.string.default_web_client_id)
    } catch (_: Exception) {
        onAuthError("Pengaturan akun Google sedang disiapkan. Silakan coba beberapa saat lagi.")
        return
    }
    val activity = context as? Activity
    if (activity == null) {
        onAuthError("Layar login belum siap. Silakan ketuk tombol Masuk dengan Google sekali lagi.")
        return
    }

    val signInOption = GetSignInWithGoogleOption.Builder(serverClientId = clientId).build()
    val primaryRequest = GetCredentialRequest.Builder()
        .addCredentialOption(signInOption)
        .build()

    scope.launch {
        try {
            val cred = try {
                credentialManager.getCredential(activity, primaryRequest).credential
            } catch (primaryEx: Exception) {
                if (primaryEx is GetCredentialCancellationException || primaryEx is CancellationException) {
                    throw primaryEx
                }
                val shouldTryGoogleIdFallback = primaryEx is NoCredentialException ||
                    primaryEx is GetCredentialProviderConfigurationException ||
                    primaryEx is GetCredentialUnsupportedException ||
                    primaryEx is GetCredentialUnknownException
                if (!shouldTryGoogleIdFallback) {
                    throw primaryEx
                }
                Log.w(TAG, "Primary SignInWithGoogle unavailable (${primaryEx::class.simpleName}), trying GetGoogleIdOption fallback")
                val fallbackOption = GetGoogleIdOption.Builder()
                    .setFilterByAuthorizedAccounts(false)
                    .setServerClientId(clientId)
                    .build()
                val fallbackRequest = GetCredentialRequest.Builder()
                    .addCredentialOption(fallbackOption)
                    .build()
                credentialManager.getCredential(activity, fallbackRequest).credential
            }

            if (cred is CustomCredential && cred.type == TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                val token = GoogleIdTokenCredential.createFrom(cred.data).idToken
                Firebase.auth.signInWithCredential(GoogleAuthProvider.getCredential(token, null)).await()
                onAuthSuccess()
            } else {
                onAuthError("Akun Google belum terbaca. Ketuk Masuk dengan Google untuk memilih akun Anda.")
            }
        } catch (e: GetCredentialCancellationException) {
            Log.w(TAG, "Google Sign-In flow cancelled or dismissed: ${e.message}", e)
            onAuthCancelled()
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            Log.e(TAG, "Google Sign-In unavailable", e)
            val friendlyMessage = when (e) {
                is NoCredentialException,
                is GetCredentialProviderConfigurationException,
                is GetCredentialUnsupportedException ->
                    "Belum ada akun Google aktif di perangkat/emulator ini. Silakan masuk akun Google di Setelan atau Play Store, lalu ketuk Masuk dengan Google."
                is FirebaseNetworkException ->
                    "Koneksi internet sedang tidak stabil. Periksa jaringan lalu ketuk Masuk dengan Google lagi."
                is FirebaseAuthException ->
                    "Verifikasi akun Google belum terhubung (${e.errorCode}). Pastikan layanan Google Play aktif dan coba lagi."
                else ->
                    "Sesi Google belum dapat terhubung sekarang. Pastikan perangkat memiliki akun Google aktif & layanan Google Play, lalu coba lagi."
            }
            onAuthError(friendlyMessage)
        }
    }
}

fun signOut(
    credentialManager: CredentialManager,
    scope: CoroutineScope,
    onBeforeSignOut: () -> Unit = {},
    onSignOutComplete: () -> Unit = {}
) {
    scope.launch {
        withContext(NonCancellable) {
            try {
                onBeforeSignOut()
                credentialManager.clearCredentialState(ClearCredentialStateRequest())
            } catch (e: Exception) {
                Log.w(TAG, "Failed to clear credential state: ${e.message}")
            } finally {
                Firebase.auth.signOut()
                onSignOutComplete()
            }
        }
    }
}
